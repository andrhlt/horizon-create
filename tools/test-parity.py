def run(check, paths, logs):
    name, script, *options = check
    log = logs / f"{name}.log"
    with log.open("w", encoding="utf-8") as output:
        result = subprocess.run(
            [sys.executable, str(ROOT / "tools" / f"{script}.py"), *paths, *options],
            cwd=ROOT, stdout=output, stderr=subprocess.STDOUT,
        )
    return name, result.returncode, log


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ("ctl", "client", "resources"):
        parser.add_argument(name, type=lambda value: Path(value).resolve(strict=True))
    parser.add_argument("--jobs", type=int, default=2)
    parser.add_argument("--check", action="append", metavar="PATTERN",
                        help="run checks by name or glob, repeat to select several groups")
    parser.add_argument("--window-culling", action="store_true",
                        help="also compare Java window and casing faces in the framebuffer (requires FFmpeg)")
    args = parser.parse_args()
    if args.jobs < 1:
        parser.error("--jobs requires at least one worker")

    checks = CHECKS
    if args.window_culling:
        checks += (
            ("window-culling", "test-window-culling"),
            ("copper-casing-ctm", "test-copper-casing-ctm"),
            ("tea-fluid-render", "test-tea-fluid-render"),
            ("encased-pipe-drain-fitting", "test-encased-pipe-drain-fitting"),
            ("encased-pipe-drain-fitting-lan", "test-encased-pipe-drain-fitting", "--lan"),
            ("copycat-window-culling", "test-copycat-window-culling"),
            ("copycat-painted-culling", "test-copycat-window-culling", "--painted"),
        )
    if args.check:
        selected = set()
        for pattern in args.check:
            matches = {check[0] for check in checks if fnmatchcase(check[0], pattern)}
            if not matches:
                parser.error(f"--check {pattern!r} did not match any check")
            selected.update(matches)
        checks = tuple(check for check in checks if check[0] in selected)

    logs = ROOT / ".local/parity"
    logs.mkdir(parents=True, exist_ok=True)
    paths = (args.ctl, args.client, args.resources)
    if "HORIZON_NO_AUDIO" in os.environ:
        os.environ.setdefault("HORIZON_CREATE_TEST_AUDIO", "1")
    failures = 0
    with ThreadPoolExecutor(max_workers=args.jobs) as pool:
        futures = [pool.submit(run, check, paths, logs) for check in checks]
        for future in as_completed(futures):
            name, status, log = future.result()
            failures += status != 0
            print(f"{'FAIL' if status else 'PASS'} {name}  {log}", flush=True)

    print(f"{len(checks) - failures}/{len(checks)} checks passed.")
    raise SystemExit(bool(failures))


if __name__ == "__main__":
    main()
